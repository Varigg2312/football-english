const CACHE_NAME = 'gaffer-pro-b57824b60351';
const OFFLINE_URL = '/offline.html';

// Core shell + content precached at install so lessons already seen
// (and the app itself) keep working with no network at all.
const PRECACHE_URLS = [
    '/', '/index.html', '/offline.html', '/404.html',
    '/football.css', '/app.js', '/i18n.js', '/sw-register.js', '/manifest.json', '/lessons.json',
    '/favicon-96.png', '/apple-touch-icon.png', '/icon-192.png', '/icon-512.png', '/icon-512-maskable.png',
    '/audio/whistle.mp3', '/audio/correct.mp3', '/audio/wrong.mp3', '/audio/win.mp3',
    '/vendor/inter-5.3.0/inter.css',
    '/vendor/inter-5.3.0/inter-latin-400-normal.woff2', '/vendor/inter-5.3.0/inter-latin-600-normal.woff2',
    '/vendor/inter-5.3.0/inter-latin-800-normal.woff2', '/vendor/inter-5.3.0/inter-latin-900-normal.woff2',
    '/vendor/fontawesome-6.5.2/css/fontawesome.min.css', '/vendor/fontawesome-6.5.2/css/solid.min.css',
    '/vendor/fontawesome-6.5.2/webfonts/fa-solid-900.woff2',
    '/vendor/canvas-confetti-1.6.0/confetti.browser.js'
];

self.addEventListener('install', (event) => {
    event.waitUntil(
        caches.open(CACHE_NAME).then(cache => Promise.all(PRECACHE_URLS.map(async (url) => {
            const res = await fetch(url, { cache: 'reload' });
            if (!res.ok) throw new Error(`precache ${url}: ${res.status}`);
            await cache.put(url, await unredirect(res));
        })))
    );
    self.skipWaiting();
});

// Cloudflare Pages 308-redirects "/x.html" to "/x" (and "/index.html" to
// "/"). A cached response that went through a redirect can't be used to
// answer a navigation — the browser rejects it — so the offline page never
// actually showed. Re-wrap such responses as plain, non-redirected ones.
async function unredirect(res) {
    if (!res.redirected) return res;
    return new Response(await res.blob(), { status: res.status, statusText: res.statusText, headers: res.headers });
}

self.addEventListener('activate', (event) => {
    event.waitUntil(
        caches.keys()
            .then(keys => Promise.all(
                keys.filter(k => k !== CACHE_NAME).map(k => caches.delete(k))
            ))
            .then(() => clients.claim())
    );
});

self.addEventListener('fetch', (event) => {
    const req = event.request;
    if (req.method !== 'GET') return;

    const url = new URL(req.url);

    // Auth/session endpoints must never be cached: a stale cached /api/auth/me
    // would instantly hand back a logged-in-as-someone-else (or logged-out)
    // response before the real network answer arrives, flashing the wrong
    // account state on every load. Bypass the SW entirely for these —
    // including navigations (the Google OAuth start/callback redirects).
    if (url.origin === self.location.origin && url.pathname.startsWith('/api/')) return;

    // Page navigations: network-first so updates show up immediately,
    // falling back to the cached shell, then the offline page.
    // ignoreSearch matters here: the installed PWA opens '/?source=pwa',
    // which must still match the precached '/' entry.
    if (req.mode === 'navigate') {
        event.respondWith(
            fetch(req)
                // Cached under the bare path: query strings here can carry
                // one-off secrets (reset-password ?token=, Stripe session_id)
                // that must not be persisted in Cache Storage.
                .then(res => { cachePut(url.origin + url.pathname, res.clone()); return res; })
                .catch(() => caches.match(req, { ignoreSearch: true })
                    // In-app routes (/lessons, /lessons/<id>, /vocabulary)
                    // are all index.html, so fall back to the cached shell
                    // for them rather than the offline page.
                    .then(cached => cached || (isAppRoute(url.pathname) ? caches.match('/') : null))
                    .then(cached => cached || caches.match(OFFLINE_URL)))
        );
        return;
    }

    if (url.origin !== self.location.origin) return; // cross-origin (YouTube, Pexels, the chat Worker): untouched

    // lessons.json: network-first so new/edited lessons show up when online,
    // but still readable offline from the last successful fetch.
    if (url.pathname.endsWith('/lessons.json')) {
        event.respondWith(
            fetch(req)
                .then(res => { cachePut(req, res.clone()); return res; })
                .catch(() => caches.match(req))
        );
        return;
    }

    // Everything else same-origin (css/js/images/audio): stale-while-revalidate.
    // Serves the cached copy immediately (or waits for the network if nothing's
    // cached yet), but always refetches in the background and updates the
    // cache for next time — so a stale entry here self-heals within one extra
    // load even without a precache refresh. CACHE_NAME itself (top of file) is
    // now a hash of every precached file's content, auto-regenerated by the
    // pre-commit hook (scripts/bump-sw-cache.js) — so a real deploy also gets
    // a fresh precache + old-cache eviction on the very first load, not just
    // this fallback. Don't hand-edit CACHE_NAME; it'll just get overwritten.
    event.respondWith(
        caches.match(req).then(cached => {
            const network = fetch(req)
                .then(res => { cachePut(req, res.clone()); return res; })
                .catch(() => cached);
            return cached || network;
        })
    );
});

function isAppRoute(pathname) {
    return /^\/(lessons(\/[\w-]+)?|vocabulary)\/?$/.test(pathname);
}

function cachePut(request, response) {
    if (!response || !response.ok) return;
    caches.open(CACHE_NAME).then(cache => cache.put(request, response));
}
